"""Graphs, automorphisms and an independent colouring checker for W2.

Vertex (r, c) of C_m x C_n (r in Z_m, c in Z_n) has index r*n + c.
"""
import itertools


def torus(m, n):
    N = m * n
    E = set()
    for r in range(m):
        for c in range(n):
            a = r * n + c
            for b in (((r + 1) % m) * n + c, r * n + (c + 1) % n):
                if a != b:
                    E.add((min(a, b), max(a, b)))
    return N, sorted(E)


def complete_bipartite(a, b):
    return a + b, [(i, a + j) for i in range(a) for j in range(b)]


def adjacency(N, E):
    adj = [set() for _ in range(N)]
    for u, v in E:
        adj[u].add(v)
        adj[v].add(u)
    return adj


def torus_automorphisms(m, n):
    """The group generated by row/column rotations, reflections and (if m == n) transpose.

    Returned as permutations p (lists): vertex v is mapped to p[v]. For m, n >= 3 these are
    automorphisms of C_m x C_n (for m, n odd >= 5, m != 4, this is the whole group, but only
    the fact that they ARE automorphisms is used)."""
    auts = []
    for dr in range(m):
        for dc in range(n):
            for sr in (1, -1):
                for sc in (1, -1):
                    for tr in ((False, True) if m == n else (False,)):
                        p = []
                        for r in range(m):
                            for c in range(n):
                                r2, c2 = (sr * r + dr) % m, (sc * c + dc) % n
                                if tr:
                                    r2, c2 = c2, r2
                                p.append(r2 * n + c2)
                        auts.append(p)
    uniq = {tuple(p) for p in auts}
    return [list(p) for p in sorted(uniq)]


def is_automorphism(p, E):
    Es = set(E)
    return all((min(p[u], p[v]), max(p[u], p[v])) in Es for u, v in E)


def colour_backtrack(N, E, L):
    """Plain backtracking: return a proper colouring c with c[v] in L[v], or None.

    Independent of any SAT code. Vertices are coloured in order of most-constrained
    (smallest remaining list) first, with forward checking."""
    adj = adjacency(N, E)
    dom = [set(L[v]) for v in range(N)]
    col = [None] * N

    def rec(left):
        if not left:
            return True
        v = min(left, key=lambda x: (len(dom[x]), x))
        for a in sorted(dom[v]):
            changed = []
            ok = True
            for u in adj[v]:
                if col[u] is None and a in dom[u]:
                    dom[u].discard(a)
                    changed.append(u)
                    if not dom[u]:
                        ok = False
            if ok:
                col[v] = a
                if rec(left - {v}):
                    return True
                col[v] = None
            for u in changed:
                dom[u].add(a)
        return False

    if rec(frozenset(range(N))):
        return col
    return None


def is_proper_list_colouring(N, E, L, c):
    return all(c[v] in L[v] for v in range(N)) and all(c[u] != c[v] for u, v in E)


def brute_force_colourable(N, E, L):
    """Fully exhaustive (product of lists) check, for tiny graphs only."""
    for phi in itertools.product(*[sorted(L[v]) for v in range(N)]):
        if all(phi[u] != phi[v] for u, v in E):
            return True
    return False


def peelable(D, f, adj):
    """True iff the vertex set D has an order in which each vertex, when removed, has fewer
    than f[w] neighbours still in D. Then G[D] is colourable from any lists with |L(w)| >= f[w]
    (colour in reverse removal order: each vertex sees fewer than f[w] coloured neighbours)."""
    D = set(D)
    deg = {w: len(adj[w] & D) for w in D}
    stack = [w for w in D if deg[w] < f[w]]
    removed = set()
    while stack:
        w = stack.pop()
        if w in removed:
            continue
        removed.add(w)
        for u in adj[w]:
            if u in D and u not in removed:
                deg[u] -= 1
                if deg[u] < f[u]:
                    stack.append(u)
    return len(removed) == len(D)
